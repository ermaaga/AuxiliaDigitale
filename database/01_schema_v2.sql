    name varchar(50) NOT NULL,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT uq_languages_code UNIQUE (code)
);

CREATE TABLE IF NOT EXISTS system.resource_keys (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key_name citext NOT NULL,
    category varchar(100) NOT NULL DEFAULT 'General',
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT uq_resource_keys_name UNIQUE (key_name)
);

CREATE TABLE IF NOT EXISTS system.resource_translations (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resource_key_id integer NOT NULL REFERENCES system.resource_keys(id) ON DELETE CASCADE,
    language_id smallint NOT NULL REFERENCES system.languages(id) ON DELETE CASCADE,
    translation_value text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at timestamptz,
    CONSTRAINT uq_resource_translation_key_lang UNIQUE (resource_key_id, language_id)
);
CREATE INDEX IF NOT EXISTS ix_resource_translations_lang ON system.resource_translations(language_id);

CREATE TABLE IF NOT EXISTS system.configurations (
    id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key varchar(100) NOT NULL,
    value text NOT NULL,
    data_type varchar(20) NOT NULL DEFAULT 'string' 
        CHECK (data_type IN ('string', 'integer', 'boolean', 'json', 'color')),
    description varchar(255),
    is_public boolean NOT NULL DEFAULT false,
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    version integer NOT NULL DEFAULT 1,
    CONSTRAINT uq_configurations_key UNIQUE (key)
);
CREATE INDEX IF NOT EXISTS ix_configurations_key ON system.configurations(key);

CREATE TABLE IF NOT EXISTS system.email_settings (
    id smallint PRIMARY KEY DEFAULT 1 CHECK (id = 1),
    smtp_server varchar(255) NOT NULL,
    smtp_port integer NOT NULL CHECK (smtp_port BETWEEN 1 AND 65535),
    enable_ssl boolean NOT NULL DEFAULT true,
    username varchar(255) NOT NULL,
    password_encrypted text NOT NULL,
    from_email citext NOT NULL CHECK (from_email ~* '^[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}$'),
    from_name varchar(150) NOT NULL,
    is_active boolean NOT NULL DEFAULT true,
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

