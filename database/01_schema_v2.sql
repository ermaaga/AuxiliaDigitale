-- ============================================================================
-- FUNZIONE AUDIT & CONCORRENZA
-- ============================================================================

CREATE OR REPLACE FUNCTION system.touch_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = clock_timestamp();
    IF TG_OP = 'UPDATE' AND (NEW IS DISTINCT FROM OLD) THEN
        NEW.version = OLD.version + 1;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

