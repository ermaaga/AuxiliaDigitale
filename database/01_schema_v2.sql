-- ============================================================================
-- SCHEMA: scheduling (Appuntamenti con vincolo GIST)
-- ============================================================================

CREATE TABLE IF NOT EXISTS scheduling.appointments (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id integer NOT NULL REFERENCES iam.users(id) ON DELETE RESTRICT,
    operator_id integer NOT NULL REFERENCES iam.users(id) ON DELETE RESTRICT,
    case_id integer REFERENCES dossier.cases(id) ON DELETE SET NULL,
    
    time_window tstzrange NOT NULL,
    status varchar(30) NOT NULL DEFAULT 'Scheduled' 
        CHECK (status IN ('Scheduled', 'Approved', 'Confirmed', 'Completed', 'Cancelled', 'NoShow')),
    notes text,
    show_in_global_calendar boolean NOT NULL DEFAULT true,
    
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at timestamptz,
    version integer NOT NULL DEFAULT 1,
    
    CONSTRAINT no_overlapping_operator_appointments 
        EXCLUDE USING gist (
            operator_id WITH =,
            time_window WITH &&
        ) WHERE (status NOT IN ('Cancelled', 'NoShow'))
);

CREATE INDEX IF NOT EXISTS ix_appointments_client ON scheduling.appointments(client_id);
CREATE INDEX IF NOT EXISTS ix_appointments_operator ON scheduling.appointments(operator_id);
CREATE INDEX IF NOT EXISTS ix_appointments_window ON scheduling.appointments USING gist (time_window);

CREATE OR REPLACE TRIGGER trg_appointments_touch
BEFORE UPDATE ON scheduling.appointments
FOR EACH ROW EXECUTE FUNCTION system.touch_updated_at();

